# ---------- exercise helpers ----------
def show_br(terms):  # terms: list of signed numbers, op shown with brackets: first plain bracket
    out = br(terms[0])
    for t in terms[1:]:
        pass
    return out
def ex_br(items):  # items: [(op, val)] first op ''
    s = ''
    for k, (op, v) in enumerate(items):
        s += (br(v) if k == 0 else f' {"+" if op=="+" else M} {br(v)}')
    return s
def reduce(items): return [v if op in ('', '+') else -v for op, v in items]
def plain(nums):
    s = fm(nums[0])
    for n in nums[1:]: s += f' {"+" if n >= 0 else M} {fm(abs(n))}'
    return s
def plainc(nums):
    s = c(nums[0])
    for n in nums[1:]: s += ' ' + c(n, ('+ ' if n >= 0 else M + ' ') + fm(abs(n)))
    return s
def num(x):
    x = round(x, 2)
    return int(x) if float(x).is_integer() else x

def opts(ans, cands):
    out = [ans]
    for d in cands + [ans + 1, ans - 1, ans + 2, -ans + 1, ans + 10, ans - 10]:
        d = num(d)
        if d not in out: out.append(d)
        if len(out) == 4: break
    return ['[[' + fm(x) + ']]' for x in out]

def staged_expl(items, wrong_hint=True):
    nums = reduce(items)
    ans = num(sum(nums))
    pos = [n for n in nums if n > 0]; neg = [n for n in nums if n < 0]
    L = ['👀 זוכרים: <b>מינוס = הנגדי</b>. מינוס לפני סוגריים הופך את מה שבפנים.']
    flips = [f'[[{M} {br(v)}]] ← [[{c(-v, sg(-v))}]]' for op, v in items[1:] if op == '-']
    if flips: L.append('🔄 ' + ' · '.join(flips))
    L.append(f'1️⃣ מורידים סוגריים: [[{plainc(nums)}]]')
    sp, sn = num(sum(pos)), num(sum(neg))
    if pos and neg:
        jp = f'[[{plain(pos)} = {fm(sp)}]]' if len(pos) > 1 else f'[[{fm(sp)}]]'
        jn = f'[[{plain(neg)} = {fm(sn)}]]' if len(neg) > 1 else f'[[{fm(sn)}]]'
        L.append(f'2️⃣ <span style="color:{G}">חיוביים יחד</span>: {jp} · <span style="color:{Rd}">שליליים יחד</span>: {jn}')
        L.append(f'3️⃣ [[{fm(sp)} {M} {fm(abs(sn))} = {fm(ans)}]]')
        if sp < abs(sn):
            L.append(f'💰 יש לי {fm(sp)} ₪ וחוב של {fm(abs(sn))} ₪ ← נשאר חוב של {fm(abs(ans))} ₪.')
        elif ans > 0:
            L.append(f'💰 יש לי {fm(sp)} ₪ וחוב של {fm(abs(sn))} ₪ ← מחזירים את החוב, נשארים {fm(ans)} ₪.')
    else:
        L.append(f'2️⃣ כולם באותו סימן ← מחברים: [[{fm(ans)}]]')
    L.append(f'✅ [[{fm(ans)}]]')
    return '<br>'.join(L), ans, nums

def two_term_expl(a, b, op):  # a op b where b may be bracket
    v = b if op == '+' else -b
    ans = num(a + v)
    L = []
    if op == '-':
        L.append(f'👀 מינוס = הנגדי: [[{fm(a)} {M} {br(b) if b<0 else fm(b)} = {fm(a)} + {br(-b)}]]')
    L.append(f'1️⃣ מתחילים ב־[[{fm(a)}]] על הציר.')
    L.append(f'2️⃣ {"מוסיפים חיובי ← זזים " + c(1,"ימינה") if v > 0 else ("מוסיפים שלילי ← זזים " + c(-1,"שמאלה") if v < 0 else "לא זזים")} {fm(abs(v))} צעדים.')
    L.append(f'✅ מגיעים ל־[[{fm(ans)}]]')
    return L, ans, v

R = []
def Q(t, l, q, o, e, d=None):
    assert len(o) == 4 and len(set(o)) == 4, (q, o)
    R.append([t, l, q, o, e, d] if d else [t, l, q, o, e])

