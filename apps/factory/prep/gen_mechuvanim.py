M = '−'
G, Rd, B, P, O = '#16a34a', '#dc2626', '#2563eb', '#7c3aed', '#ea580c'

def fm(n):
    if isinstance(n, float) and n.is_integer(): n = int(n)
    s = str(abs(n))
    return (M + s) if n < 0 else s
def sg(n):  # signed with + for positives
    return fm(n) if n < 0 else ('+' + fm(n) if n > 0 else '0')
def br(n): return '(' + sg(n) + ')'
def c(n, t=None):
    col = G if n > 0 else (Rd if n < 0 else '#6b7280')
    return f"<span style='color:{col}'>{t if t is not None else fm(n)}</span>"
BOX = "<span style='display:inline-block;width:26px;height:22px;border:2px solid #7c3aed;border-radius:5px;vertical-align:middle'></span>"

# ---------- number line SVG ----------
def nl(lo, hi, marks=(), jumps=(), w=300, h=None, letters=False, show_nums=True):
    jh = 46 if jumps else 0
    h = h or (70 + jh)
    y = 34 + jh
    X = lambda v: 16 + (v - lo) * (w - 32) / (hi - lo)
    s = [f'<svg viewBox="0 0 {w} {h}" width="{w}" style="direction:ltr;overflow:visible"><rect width="{w}" height="{h}" rx="10" fill="#fff"/>',
         f'<line x1="6" y1="{y}" x2="{w-6}" y2="{y}" stroke="#111" stroke-width="2"/>',
         f'<path d="M{w-6},{y} l-8,-5 v10 z" fill="#111"/><path d="M6,{y} l8,-5 v10 z" fill="#111"/>']
    for v in range(lo, hi + 1):
        big = v == 0
        s.append(f'<line x1="{X(v):.1f}" y1="{y-(8 if big else 5)}" x2="{X(v):.1f}" y2="{y+(8 if big else 5)}" stroke="#111" stroke-width="{2.5 if big else 1.2}"/>')
        if show_nums or v == 0:
            s.append(f'<text x="{X(v):.1f}" y="{y+22}" font-size="{12 if big else 10}" font-weight="{"bold" if big else "normal"}" text-anchor="middle" fill="{"#111" if big else "#6b7280"}">{fm(v)}</text>')
    for (a, b, col, lab, d) in jumps:
        x1, x2 = X(a), X(b); mid = (x1 + x2) / 2; top = y - 12 - min(40, abs(x2 - x1) * .35 + 14)
        cls = f'class="dr" pathLength="1" style="animation-delay:{d}s;animation-duration:1.2s"' if d is not None else ''
        s.append(f'<path d="M{x1:.1f},{y-6} Q{mid:.1f},{top:.1f} {x2:.1f},{y-6}" fill="none" stroke="{col}" stroke-width="3" {cls}/>')
        dir_ = 1 if b > a else -1
        an = f'class="ap" style="animation-delay:{d+1.1}s"' if d is not None else ''
        s.append(f'<path {an} d="M{x2:.1f},{y-6} l{-9*dir_},-6 l{2*dir_},9 z" fill="{col}"/>')
        s.append(f'<text {an} x="{mid:.1f}" y="{top+12:.1f}" font-size="13" font-weight="bold" fill="{col}" text-anchor="middle">{lab}</text>')
    for (v, lab, col, d) in marks:
        an = f'class="dp" style="animation-delay:{d}s"' if d is not None else ''
        s.append(f'<g {an}><circle cx="{X(v):.1f}" cy="{y}" r="6.5" fill="{col}" stroke="#111"/><text x="{X(v):.1f}" y="{y-12}" font-size="14" font-weight="bold" fill="{col}" text-anchor="middle">{lab}</text></g>')
    s.append('</svg>')
    return ''.join(s)

